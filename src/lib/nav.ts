export function menuKeyForPath(pathname: string): MenuKey | null {
  // Static export serves /foo/ — compare without the trailing slash.
  const path = pathname.length > 1 ? pathname.replace(/\/+$/, "") : pathname;
  const hits = ROUTE_KEYS.filter(([p]) =>
    p.endsWith("$") ? path === p.slice(0, -1) : path === p || path.startsWith(p + "/"),
  ).sort((a, b) => b[0].length - a[0].length);
  return hits[0]?.[1] ?? null;
}

