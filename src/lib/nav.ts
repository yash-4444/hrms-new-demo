export interface NavItem {
  label: string;
  href: string;
  icon: LucideIcon;
  menuKey: MenuKey;
  /** shown as a count chip in the sidebar */
  badge?: "approvals" | "exceptions" | "tickets";
  /** Hidden when the persona can view this key — the fuller entry for the same
      screen lives in another group (e.g. My Expenses vs Workplace › Expenses). */
  hideIf?: MenuKey;
}

/** Whether a nav item shows for a persona (its grant, minus `hideIf`). */
export function navItemVisible(item: NavItem, can: (key: MenuKey, action?: "V") => boolean) {
  return can(item.menuKey, "V") && !(item.hideIf && can(item.hideIf, "V"));
}

